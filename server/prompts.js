export function passageBlock(sentences, level) {
  const paras = new Map();
  for (const s of sentences) {
    if (!paras.has(s.paragraph)) paras.set(s.paragraph, []);
    paras.get(s.paragraph).push(`[S${s.index}] ${s.text}`);
  }
  const body = [...paras.entries()]
    .map(([p, lines]) => `<paragraph number="${p}">\n${lines.join('\n')}\n</paragraph>`)
    .join('\n');
  return `학습자 수준: ${LEVELS[level] || LEVELS.high2}
지문은 총 ${sentences.length}개 문장, ${paras.size}개 문단입니다. 각 문장 앞에 번호가 붙어 있습니다.

<passage>
${body}
</passage>`;
}

